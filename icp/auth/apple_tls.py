def _build_context() -> ssl.SSLContext:
    context = ssl.create_default_context()
    context.load_verify_locations(cafile=requests.certs.where())
    context.load_verify_locations(cadata=APPLE_ROOT_CA_PEM)
    return context


class _AppleTLSAdapter(HTTPAdapter):
    def __init__(self, context: ssl.SSLContext):
        self._context = context
        super().__init__()

    def init_poolmanager(self, connections, maxsize, block=False, **pool_kwargs):
        pool_kwargs["ssl_context"] = self._context
        return super().init_poolmanager(connections, maxsize, block=block, **pool_kwargs)

    def proxy_manager_for(self, proxy, **proxy_kwargs):
        proxy_kwargs["ssl_context"] = self._context
        return super().proxy_manager_for(proxy, **proxy_kwargs)


_session: requests.Session | None = None
_session_lock = threading.Lock()


def session() -> requests.Session:
    global _session
    if _session is None:
        with _session_lock:
            if _session is None:
                configured = requests.Session()
                configured.mount("https://", _AppleTLSAdapter(_build_context()))
                _session = configured
    return _session


def new_session() -> requests.Session:
    """A session with Apple Root CA trust and no connection reuse (one request, then closed by
    the caller or garbage collection)."""
    configured = requests.Session()
    configured.mount("https://", _AppleTLSAdapter(_build_context()))
    return configured


def request_once(method: str, url: str, **kwargs):
    """Send a request without connection reuse."""
    configured = requests.Session()
    configured.mount("https://", _AppleTLSAdapter(_build_context()))
    try:
        response = configured.request(method, url, **kwargs)
        _ = response.content
        return response
    finally:
        configured.close()


def get(url, **kwargs):
    return session().get(url, **kwargs)


def post(url, **kwargs):
    return session().post(url, **kwargs)


def put(url, **kwargs):
    return session().put(url, **kwargs)
